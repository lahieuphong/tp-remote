import { describe, expect, it } from "vitest";

import validFixture from "../../../../tests/fixtures/ipc/app-info.valid.json";
import type { AppInfo } from "../bindings";
import { CoreApiError } from "../core-api/errors";
import { parseAppInfo } from "../core-api/parseAppInfo";

// Same fixture files as crates/tp-contracts/tests/ipc_fixtures.rs.
const invalidFixtures = import.meta.glob<unknown>("../../../../tests/fixtures/ipc/invalid/*.json", {
  eager: true,
  import: "default",
});

const bindingSources = import.meta.glob<string>("../bindings/*.ts", {
  eager: true,
  query: "?raw",
  import: "default",
});

const TS_RS_HEADER =
  "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.";
const INDEX_HEADER =
  "// This file was generated by tp-bindings (crates/tp-test-harness). Do not edit this file manually.";

describe("AppInfo contract (Rust ↔ TypeScript)", () => {
  it("accepts the fixture that Rust serializes, unchanged", () => {
    const parsed: AppInfo = parseAppInfo(validFixture);
    expect(parsed).toEqual(validFixture);
  });

  it("rejects every invalid fixture that Rust also rejects", () => {
    const names = Object.keys(invalidFixtures).sort();
    expect(names.map((n) => n.split("/").pop())).toEqual([
      "bad-enum.json",
      "bad-nested-enum.json",
      "missing-field.json",
      "unknown-field.json",
      "wrong-type.json",
    ]);
    for (const name of names) {
      expect(() => parseAppInfo(invalidFixtures[name]), name).toThrow(CoreApiError);
      try {
        parseAppInfo(invalidFixtures[name]);
      } catch (error) {
        expect((error as CoreApiError).code, name).toBe("invalidResponse");
      }
    }
  });

  it("rejects non-objects and null webview fields of the wrong type", () => {
    for (const raw of [null, [], "AppInfo", 1]) {
      expect(() => parseAppInfo(raw)).toThrow(CoreApiError);
    }
    expect(() =>
      parseAppInfo({ ...validFixture, shell: { tauriVersion: "2", webviewVersion: 155 } }),
    ).toThrow(CoreApiError);
  });

  it("accepts a null webview version", () => {
    const parsed = parseAppInfo({
      ...validFixture,
      shell: { tauriVersion: "2.12.5", webviewVersion: null },
    });
    expect(parsed.shell.webviewVersion).toBeNull();
  });

  it("uses only bindings generated from Rust", () => {
    const files = Object.entries(bindingSources);
    expect(files.length).toBe(21); // 11 in BOOT-01, plus 10 CAP-02A preview types
    for (const [path, source] of files) {
      const header = path.endsWith("/index.ts") ? INDEX_HEADER : TS_RS_HEADER;
      expect(source.startsWith(header), path).toBe(true);
    }
  });
});
