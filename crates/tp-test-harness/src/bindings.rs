//! TypeScript bindings for the IPC DTOs in `tp-contracts`, generated with ts-rs.
//!
//! Output is deterministic: a fixed type list, `ts_rs::Config::new()` (environment
//! variables such as `TS_RS_LARGE_INT` are ignored) and files sorted by name. The output
//! directory is owned by the generator: `.ts` files it does not produce are reported as
//! drift by [`check`] and removed by [`write`].

use std::collections::BTreeMap;
use std::path::Path;

use tp_contracts::ipc::{
    AppInfo, BuildProfile, EngineModuleStatus, IpcError, IpcErrorCode, PlatformInfo,
    ProtocolSupport, RemoteFeatures, ShellInfo,
};
use tp_contracts::module::ModuleState;
use ts_rs::{Config, TS};

/// First line ts-rs writes into every generated type file.
pub const TS_RS_HEADER: &str = "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.";

const INDEX_HEADER: &str = "// This file was generated by tp-bindings (crates/tp-test-harness). Do not edit this file manually.";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    pub name: String,
    pub contents: String,
}

fn type_file<T: TS + 'static>(cfg: &Config) -> Result<GeneratedFile, String> {
    let type_name = std::any::type_name::<T>();
    let path = T::output_path().ok_or_else(|| format!("{type_name} cannot be exported"))?;
    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or_else(|| format!("{type_name} has no file name"))?
        .to_owned();
    let contents = T::export_to_string(cfg).map_err(|e| format!("{type_name}: {e}"))?;
    Ok(GeneratedFile { name, contents })
}

/// Generates every binding file, plus `index.ts` re-exporting all types.
pub fn generate() -> Result<Vec<GeneratedFile>, String> {
    let cfg = Config::new();
    let mut files = vec![
        type_file::<AppInfo>(&cfg)?,
        type_file::<PlatformInfo>(&cfg)?,
        type_file::<BuildProfile>(&cfg)?,
        type_file::<ProtocolSupport>(&cfg)?,
        type_file::<ShellInfo>(&cfg)?,
        type_file::<RemoteFeatures>(&cfg)?,
        type_file::<EngineModuleStatus>(&cfg)?,
        type_file::<ModuleState>(&cfg)?,
        type_file::<IpcError>(&cfg)?,
        type_file::<IpcErrorCode>(&cfg)?,
    ];
    files.sort_by(|a, b| a.name.cmp(&b.name));

    let mut index = format!("{INDEX_HEADER}\n\n");
    for file in &files {
        let module = file.name.trim_end_matches(".ts");
        index.push_str(&format!(
            "export type {{ {module} }} from \"./{module}\";\n"
        ));
    }
    files.push(GeneratedFile {
        name: "index.ts".to_owned(),
        contents: index,
    });
    Ok(files)
}

fn existing_ts_files(dir: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut found = BTreeMap::new();
    if !dir.exists() {
        return Ok(found);
    }
    let entries = std::fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("read {}: {e}", dir.display()))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.ends_with(".ts") {
            let contents =
                std::fs::read_to_string(entry.path()).map_err(|e| format!("read {name}: {e}"))?;
            found.insert(name, contents);
        }
    }
    Ok(found)
}

/// Writes the bindings into `dir`, removing stale `.ts` files. Returns the file count.
pub fn write(dir: &Path) -> Result<usize, String> {
    let files = generate()?;
    std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    for stale in existing_ts_files(dir)?.keys() {
        if !files.iter().any(|f| &f.name == stale) {
            std::fs::remove_file(dir.join(stale)).map_err(|e| format!("remove {stale}: {e}"))?;
        }
    }
    for file in &files {
        std::fs::write(dir.join(&file.name), &file.contents)
            .map_err(|e| format!("write {}: {e}", file.name))?;
    }
    Ok(files.len())
}

/// Compares `dir` with freshly generated bindings. Returns one message per difference.
pub fn check(dir: &Path) -> Result<(), Vec<String>> {
    let files = generate().map_err(|e| vec![e])?;
    let existing = existing_ts_files(dir).map_err(|e| vec![e])?;
    let mut drift = Vec::new();
    for file in &files {
        match existing.get(&file.name) {
            None => drift.push(format!("missing: {}", file.name)),
            Some(contents) if contents != &file.contents => {
                drift.push(format!("out of date: {}", file.name));
            }
            Some(_) => {}
        }
    }
    for name in existing.keys() {
        if !files.iter().any(|f| &f.name == name) {
            drift.push(format!("not generated (remove it): {name}"));
        }
    }
    if drift.is_empty() { Ok(()) } else { Err(drift) }
}
